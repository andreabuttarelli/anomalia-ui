#!/usr/bin/env node
/**
 * Generates the agent skill's reference files from the system itself.
 *
 * The skill tells an agent which component to use and which token to reach for.
 * If those lists are hand-written they rot — and a skill that documents a prop
 * that no longer exists is worse than no skill, because the agent trusts it.
 * So both files are emitted from the same sources the library and docs use:
 * `src/docs/catalog.ts` for the component API, `tokens.css` + `theme.css` for
 * the tokens.
 *
 *     npm run skill:reference
 */

import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { catalog, CATEGORY_ORDER } from '../src/docs/catalog.ts';
import { palettes, readBlock, resolveToken } from './lib/css-tokens.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = resolve(root, 'skills/anomalia-ui/references');
mkdirSync(outDir, { recursive: true });

const stamp = '<!-- Generated by scripts/generate-skill-reference.mjs — do not edit by hand. -->';

/* ── components.md ───────────────────────────────────────────────────────── */

const componentLines = [
  stamp,
  '',
  '# Component reference',
  '',
  'Every export, what it is for, and the props that are not obvious. Anything not',
  'listed is still forwarded to the root element (including `class`), because each',
  'component spreads its rest props.',
  '',
  '## Index',
  ''
];

for (const category of CATEGORY_ORDER) {
  const items = catalog.filter((entry) => entry.category === category);
  if (items.length === 0) continue;
  componentLines.push(`- **${category}** — ${items.map((i) => i.exports.join(', ')).join(', ')}`);
}

for (const category of CATEGORY_ORDER) {
  const items = catalog.filter((entry) => entry.category === category);
  if (items.length === 0) continue;

  componentLines.push('', `## ${category}`, '');

  for (const entry of items) {
    componentLines.push(`### ${entry.exports.join(' · ')}`, '', entry.summary, '');

    if (entry.notes?.length) {
      for (const note of entry.notes) componentLines.push(`- ${note}`);
      componentLines.push('');
    }

    for (const group of entry.props ?? []) {
      if (group.title) componentLines.push(`**${group.title}**`, '');
      componentLines.push('| Prop | Type | Default | Notes |', '| --- | --- | --- | --- |');
      for (const row of group.rows) {
        const escape = (value) => String(value).replace(/\|/g, '\\|');
        componentLines.push(
          `| \`${escape(row.name)}\` | \`${escape(row.type)}\` | ${row.default ? `\`${escape(row.default)}\`` : '—'} | ${escape(row.description)} |`
        );
      }
      componentLines.push('');
    }
  }
}

writeFileSync(resolve(outDir, 'components.md'), componentLines.join('\n') + '\n');

/* ── tokens.md ───────────────────────────────────────────────────────────── */

const { primitives, light, dark, themeCss } = palettes();

/** Semantic names are the ones components read — list those, not the palette. */
const semantic = Object.keys(readBlock(themeCss, ':root {'));

const groups = [
  ['Surfaces', (name) => name.startsWith('--an-surface') || name === '--an-bg' || name === '--an-glass-blur'],
  ['Content', (name) => name.startsWith('--an-text')],
  ['Lines', (name) => name.startsWith('--an-border')],
  ['Interactive', (name) => name.startsWith('--an-accent') || name.startsWith('--an-on-accent') || name === '--an-ring'],
  ['Brand', (name) => name.startsWith('--an-brand') || name === '--an-on-brand'],
  ['Status', (name) => /^--an-(success|warning|danger|info|on-status)/.test(name)],
  ['Effects', (name) => name.startsWith('--an-shadow') || name === '--an-scrim']
];

const tokenLines = [
  stamp,
  '',
  '# Token reference',
  '',
  'Components read the **semantic** layer only. Override these to restyle; never',
  'override a component selector, and never hard-code a colour, radius or duration',
  'in app code.',
  '',
  'Values below are resolved: `var()` chains and `color-mix()` are shown as they',
  'compute, for both themes.',
  ''
];

const cell = (token, palette) => {
  const raw = palette[token];
  if (raw === undefined) return '—';
  const resolved = resolveToken(raw, palette);
  return `\`${resolved.length > 44 ? `${resolved.slice(0, 41)}…` : resolved}\``;
};

for (const [title, match] of groups) {
  const names = semantic.filter(match);
  if (names.length === 0) continue;

  tokenLines.push(`## ${title}`, '', '| Token | Light | Dark |', '| --- | --- | --- |');
  for (const name of names) {
    tokenLines.push(`| \`${name}\` | ${cell(name, light)} | ${cell(name, dark)} |`);
  }
  tokenLines.push('');
}

/** Scales live in tokens.css and are theme-independent. */
const scales = [
  ['Type', (name) => name.startsWith('--an-text-') || name.startsWith('--an-font') || name.startsWith('--an-weight')],
  ['Space', (name) => name.startsWith('--an-space-')],
  ['Radius', (name) => name.startsWith('--an-radius-')],
  ['Controls', (name) => name.startsWith('--an-control-') || name === '--an-tap-target' || name.startsWith('--an-focus-')],
  ['Motion', (name) => name.startsWith('--an-duration-') || name.startsWith('--an-ease-')],
  ['State layers', (name) => name.startsWith('--an-state-') || name.startsWith('--an-disabled-') || name === '--an-ripple-opacity' || name === '--an-press-scale'],
  ['Layering', (name) => name.startsWith('--an-z-')]
];

for (const [title, match] of scales) {
  const names = Object.keys(primitives).filter(match);
  if (names.length === 0) continue;

  tokenLines.push(`## ${title}`, '', '| Token | Value |', '| --- | --- |');
  for (const name of names) {
    tokenLines.push(`| \`${name}\` | \`${resolveToken(primitives[name], primitives)}\` |`);
  }
  tokenLines.push('');
}

writeFileSync(resolve(outDir, 'tokens.md'), tokenLines.join('\n') + '\n');

console.log(
  `Wrote skills/anomalia-ui/references/components.md (${catalog.length} entries) and tokens.md (${semantic.length} semantic tokens).`
);
